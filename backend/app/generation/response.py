import re
from typing import Any


def extract_citation_ids(answer: str) -> list[int]:
    """
    Extract citation IDs from an LLM answer.

    Example:
        "... state is persisted [1] and resumes [4]."

    Returns:
        [1, 4]
    """

    matches = re.findall(r"\[(\d+)\]", answer)

    # Preserve order while removing duplicates.
    return list(dict.fromkeys(int(match) for match in matches))


def remove_inline_citation_markers(answer: str) -> str:
    """Keep citations in structured metadata instead of answer prose."""
    return re.sub(r"\s*\[\d+\]", "", answer).rstrip()


def build_structured_citations(
    answer: str,
    results: list[dict],
) -> list[dict[str, Any]]:
    """
    Resolve the citation IDs generated by the LLM
    to the corresponding retrieved chunks.

    The LLM citation number refers to the original
    context item number, NOT the final citation sequence.
    """

    citation_ids = extract_citation_ids(answer)

    citations = []

    for citation_id in citation_ids:

        # LLM uses 1-based context numbering.
        index = citation_id - 1

        if index < 0 or index >= len(results):
            citations.append(
                {
                    "id": citation_id,
                    "valid": False,
                    "error": (
                        "Citation refers to a context item "
                        "that was not retrieved."
                    ),
                }
            )
            continue

        result = results[index]
        chunk = result["chunk"]

        citations.append(
            {
                "id": citation_id,
                "valid": True,

                # Document metadata
                "source": chunk["source"],
                "page": chunk.get("page"),
                "section": chunk.get("section"),
                "chunk_id": chunk["chunk_id"],
                "text": chunk["text"],

                # Retrieval evidence
                "retrieval": {
                    "dense_rank": result.get("dense_rank"),
                    "dense_score": result.get("dense_score"),
                    "bm25_rank": result.get("bm25_rank"),
                    "bm25_score": result.get("bm25_score"),
                    "rrf_score": result.get("rrf_score"),
                    "decision": result.get(
                        "retrieval_decision"
                    ),
                },
            }
        )

    return citations
